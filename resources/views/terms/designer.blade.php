<h2 class="text-lg font-bold text-slate-900 mb-3">Ketentuan Layanan Desainer</h2>

<p class="text-sm text-slate-600 mb-4">
    Dengan mendaftar dan menggunakan layanan ARTIV sebagai desainer, kamu menyatakan telah membaca,
    memahami, dan menyetujui seluruh ketentuan berikut:
</p>

<ol class="list-decimal list-inside space-y-3 text-sm text-slate-600">

    <li>
        <strong>Kewajiban Penyelesaian Pesanan.</strong>
        Kamu wajib menyelesaikan pesanan sesuai tenggat waktu (deadline) yang disepakati
        pada saat menerima pesanan. Keterlambatan tanpa pemberitahuan dapat dikenakan sanksi
        sesuai kebijakan ARTIV.
    </li>

    <li>
        <strong>Orisinalitas Karya.</strong>
        Kamu menjamin bahwa seluruh karya yang dihasilkan merupakan karya orisinal dan tidak
        melanggar hak kekayaan intelektual pihak lain. Kamu dilarang menyalin, meniru, atau
        menggunakan karya pihak lain tanpa izin tertulis.
    </li>

    <li>
        <strong>Komunikasi Melalui Platform.</strong>
        Seluruh komunikasi terkait pesanan wajib dilakukan melalui platform ARTIV. Komunikasi
        di luar platform yang bertujuan menghindari sistem tidak diakui dan dapat dikenakan sanksi.
    </li>

    <li>
        <strong>Pembatalan Pesanan.</strong>
        Pembatalan pesanan hanya diperbolehkan dengan alasan yang sah dan dapat
        dipertanggungjawabkan, seperti sakit berat, keadaan darurat, atau kendala teknis
        yang tidak dapat dihindari. Pembatalan wajib disertai alasan tertulis melalui fitur
        pembatalan pada platform.
    </li>

    <li>
        <strong>Bagi Hasil (Revenue Sharing).</strong>
        Setiap pesanan yang berhasil diselesaikan akan dibagi hasil dengan ketentuan:
        <ul class="list-disc list-inside mt-2 space-y-1 text-slate-600">
            <li><strong>90% (sembilan puluh persen)</strong> dari nilai pesanan menjadi hak desainer.</li>
            <li><strong>10% (sepuluh persen)</strong> dari nilai pesanan menjadi hak ARTIV sebagai biaya layanan platform.</li>
        </ul>
        Pembagian dilakukan setelah pesanan dinyatakan selesai dan pembayaran dari customer telah lunas.
    </li>

    <li>
        <strong>Pembatalan oleh Desainer dan Dampak Finansial.</strong>
        Apabila kamu membatalkan pesanan yang sedang dikerjakan, dan pesanan tersebut kemudian
        dialihkan serta diselesaikan oleh desainer lain, maka:
        <ul class="list-disc list-inside mt-2 space-y-1 text-slate-600">
            <li>Kamu <strong>tidak berhak</strong> atas sebagian maupun seluruh pembayaran dari pesanan tersebut.</li>
            <li>Seluruh hak bagi hasil atas pesanan tersebut beralih sepenuhnya kepada desainer pengganti.</li>
            <li>Pekerjaan yang telah kamu lakukan sebelum pembatalan tidak dapat diklaim sebagai dasar pembayaran.</li>
        </ul>
    </li>

    <li>
        <strong>Hak Kekayaan Intelektual.</strong>
        Hak cipta atas karya tetap melekat pada desainer dan/atau ARTIV. Setelah pembayaran lunas
        dan pesanan selesai, customer memperoleh hak penggunaan karya sesuai brief. ARTIV berhak
        menampilkan karya yang telah selesai pada galeri publik platform sebagai portofolio,
        kecuali kamu menyatakan keberatan secara tertulis.
    </li>

    <li>
        <strong>Kerahasiaan Data.</strong>
        Kamu wajib menjaga kerahasiaan data customer, termasuk namun tidak terbatas pada
        identitas, brief, dan file referensi yang diberikan. Data tersebut hanya boleh
        digunakan untuk keperluan penyelesaian pesanan.
    </li>

    <li>
        <strong>Sanksi dan Penangguhan Akun.</strong>
        Pelanggaran terhadap ketentuan ini dapat mengakibatkan peringatan, pembatasan akses,
        penangguhan akun, hingga penghapusan akun secara permanen, sesuai tingkat pelanggaran
        yang dilakukan.
    </li>

    <li>
        <strong>Perubahan Ketentuan.</strong>
        ARTIV berhak mengubah ketentuan ini sewaktu-waktu. Perubahan akan diberitahukan melalui
        platform, dan kamu akan diminta menyetujui ulang ketentuan yang diperbarui sebelum
        dapat melanjutkan penggunaan layanan.
    </li>

</ol>

